"""Render the OTA release notes as a firmware-native 216x208 monochrome bitmap."""
import json
from pathlib import Path
import re
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]

def render():
    notes = json.loads((ROOT / "app/page/update_notes.json").read_text(encoding="utf-8"))
    image = Image.new("1", (216, 208), 0)
    draw = ImageDraw.Draw(image)
    font_path = Path("C:/Windows/Fonts/msyh.ttc")
    title_font = ImageFont.truetype(str(font_path), 22)
    body_font = ImageFont.truetype(str(font_path), 16)
    def line(y, text, font):
        if draw.textlength(text, font=font) > 208:
            raise ValueError("Release note line is too wide: " + text)
        draw.text((4, y), text, font=font, fill=1, anchor="lt")
    if len(notes["changes"]) > 4:
        raise ValueError("At most four release note lines fit on the display")
    line(4, notes["title"], title_font)
    for index, text in enumerate(notes["changes"]):
        line(43 + index * 31, f"{index + 1}. {text}", body_font)
    line(182, notes["footer"], body_font)
    bits = image.tobytes()
    assert len(bits) == 5616
    header = "/* Generated by ota/render_update_notes.py; edit update_notes.json. */\n"
    header += "#ifndef WC_UPDATE_NOTES_BITMAP_H\n#define WC_UPDATE_NOTES_BITMAP_H\n\n"
    header += "static const uint8_t update_notes_bitmap[5616] = {\n"
    for offset in range(0, len(bits), 24):
        header += "    " + ", ".join(f"0x{byte:02x}" for byte in bits[offset:offset+24]) + ",\n"
    header += "};\n\n#endif\n"
    (ROOT / "app/page/update_notes_bitmap.h").write_text(header, encoding="ascii")
    out = ROOT / "ota/build"
    out.mkdir(parents=True, exist_ok=True)
    version = re.search(r'#define APP_VERSION\s+"([^"]+)"',
                        (ROOT / "app/app.h").read_text(encoding="utf-8"))[1]
    preview = Image.new("RGB", (240, 320), (12, 22, 32))
    preview_draw = ImageDraw.Draw(preview)
    preview_draw.rectangle((0, 0, 239, 52), fill=(24, 48, 66))
    preview_draw.text((16, 10), "OTA UPDATED", font=body_font, fill="white", anchor="lt")
    preview_draw.text((16, 30), version, font=body_font, fill=(120, 215, 246), anchor="lt")
    panel = Image.new("RGB", (216, 208), (8, 20, 32))
    panel.paste((255, 255, 255), mask=image)
    preview.paste(panel, (12, 64))
    preview_draw.text((16, 286), "K3: Back to clock", font=body_font, fill="white", anchor="lt")
    preview.save(out / "update-notice-preview.png")
    print("Rendered OTA release notes (5616 bytes)")

if __name__ == "__main__":
    render()
